"""Build the single-file LocationSpoofer executable with PyInstaller.

Usage (CI runs this on windows-latest):
    python packaging/build_exe.py --version 1.1.42
Output: dist/LocationSpoofer.exe (dist/LocationSpoofer on macOS/Linux)
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUILD_FILE = ROOT / "spoofer" / "_build.py"

# pymobiledevice3 imports most of its modules lazily (importlib), and several dependencies
# ship data files (sea-lane network, wintun.dll, trace codes), so they are collected whole.
COLLECT_ALL = [
    "pymobiledevice3",
    "searoute",
    "pytun_pmd3",
    "developer_disk_image",
    "pmd_pytcp",
    "pmd_net_proto",
    "pmd_net_addr",
    "ipsw_parser",
    "pykdebugparser",
    "typer_injector",
]
COLLECT_SUBMODULES = ["uvicorn", "spoofer"]
# Large packages pymobiledevice3 only uses for interactive/developer extras we never call.
EXCLUDE = ["tkinter", "matplotlib", "IPython", "jedi", "parso", "pytest"]


def dependency_closure(roots: list[str]) -> list[str]:
    """Every installed distribution the app depends on (recursively). Several of them call
    importlib.metadata.version() on themselves at import time, so their metadata must be bundled."""
    import importlib.metadata as md

    seen: dict[str, str] = {}
    stack = list(roots)
    while stack:
        name = stack.pop()
        key = re.sub(r"[-_.]+", "-", name).lower()
        if key in seen:
            continue
        try:
            dist = md.distribution(name)
        except md.PackageNotFoundError:
            continue
        seen[key] = dist.metadata["Name"]
        for req in dist.requires or []:
            if "extra ==" in req:
                continue
            marker_ok = True
            if ";" in req:
                try:
                    from packaging.requirements import Requirement

                    r = Requirement(req)
                    marker_ok = r.marker is None or r.marker.evaluate()
                except Exception:
                    marker_ok = True
            if marker_ok:
                stack.append(re.split(r"[ ;<>=!~\[(]", req, maxsplit=1)[0])
    return sorted(seen.values(), key=str.lower)


def requirement_roots() -> list[str]:
    roots = []
    for line in (ROOT / "requirements.txt").read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            roots.append(re.split(r"[ ;<>=!~\[(]", line, maxsplit=1)[0])
    return roots


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", required=True, help="release version, e.g. 1.1.42")
    ap.add_argument("--onedir", action="store_true", help="folder build instead of one file (debugging)")
    args = ap.parse_args()
    if not re.fullmatch(r"\d+\.\d+\.\d+", args.version):
        ap.error("version must look like 1.2.3")

    original = BUILD_FILE.read_text(encoding="utf-8")
    BUILD_FILE.write_text(
        "# Generated by packaging/build_exe.py\n" f'BUILD_VERSION = "{args.version}"\n', encoding="utf-8"
    )
    sep = os.pathsep
    pyi_args = [
        str(ROOT / "packaging" / "launcher.py"),
        "--name", "LocationSpoofer",
        "--noconfirm",
        "--clean",
        "--console",  # the console window is the app's "on" switch and shows its log
        "--distpath", str(ROOT / "dist"),
        "--workpath", str(ROOT / "build"),
        "--specpath", str(ROOT / "build"),
        "--paths", str(ROOT),
        "--add-data", f"{ROOT / 'spoofer' / 'static'}{sep}spoofer/static",
    ]
    pyi_args.append("--onedir" if args.onedir else "--onefile")
    for pkg in COLLECT_ALL:
        pyi_args += ["--collect-all", pkg]
    for pkg in COLLECT_SUBMODULES:
        pyi_args += ["--collect-submodules", pkg]
    for dist in dependency_closure(requirement_roots()):
        pyi_args += ["--copy-metadata", dist]
    for pkg in EXCLUDE:
        pyi_args += ["--exclude-module", pkg]
    icon = ROOT / "packaging" / "icon.ico"
    if icon.exists():
        pyi_args += ["--icon", str(icon)]

    import PyInstaller.__main__

    try:
        PyInstaller.__main__.run(pyi_args)
    finally:
        BUILD_FILE.write_text(original, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
